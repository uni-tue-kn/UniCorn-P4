"""The controller's target contract.

Metadata helpers return the shared table/resource JSON schema. The native wire
messages and metadata remain private to each implementation. Resource managers
share read/write/reset methods; capabilities describe unavailable operations.
"""
from typing import Protocol


class TargetBackend(Protocol):
    target: str
    connected: bool
    resources: object
    p4_helper: object

    def connect(self): ...
    def shutdown(self): ...
    def initialize_bundle(self, bundle: dict, keep_entries: bool = False): ...
    def get_loaded_config(self) -> dict: ...
    def capabilities(self) -> dict: ...
    def as_json(self) -> dict: ...
    def manager(self, kind: str): ...
    def create_table_entry(self, value, is_json: bool = True): ...
    def get_table_entries(self, name=None) -> dict: ...
    def write_table_entry(self, entry): ...
    def delete_table_entry(self, entry): ...
    def update_table_entry(self, old, new): ...
    def table_entry_key(self, entry): ...
    def get_counter_values(self, counter_id=None, index=None) -> dict: ...
    def get_direct_counter_values(self, table_id=None) -> dict: ...
    def reset_counter(self, counter_id, index=None) -> int: ...
    def reset_direct_counter(self, table_id, table_entry=None) -> int: ...
